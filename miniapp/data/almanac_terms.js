const GENERAL_NOTE = '这是通用黄历日期资料，不代表对本人适宜，也不能单独作为现实决策依据。'

function getAlmanacTermMeaning(term) {
  return Object.prototype.hasOwnProperty.call(meanings, term) ? meanings[term] : '该词释义待补充，请以原始黄历条目为准。'
}

function showAlmanacTerm(event) {
  const { term, kind } = event.currentTarget.dataset
  if (typeof term !== 'string' || !term || (kind !== '宜' && kind !== '忌')) return
  wx.showModal({
    title: `${kind} · ${term}`,
    content: `${getAlmanacTermMeaning(term)}\n\n${GENERAL_NOTE}`,
    showCancel: false,
    confirmText: '知道了',
  })
}

module.exports = { meanings, getAlmanacTermMeaning, showAlmanacTerm }
